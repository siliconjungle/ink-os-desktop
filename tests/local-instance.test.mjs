import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { LocalInstance, localPort } from '../src/local-instance.mjs';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';

test('desktop lifecycle owns a clean local instance and authenticates with its generated credential', { timeout: 20000 }, async t => {
  const directory = await mkdtemp(join(tmpdir(), 'ink-desktop-'));
  const port = await localPort(directory);
  const electron = process.env.INK_TEST_ELECTRON === '1';
  const instance = new LocalInstance({ platformDirectory: process.env.INK_OS_PLATFORM_DIR || resolve('../ink-os-platform'), directory, port, ...(electron ? { executable: createRequire(import.meta.url)('electron'), electron: true } : {}) });
  const abort = new AbortController();
  t.after(async () => { abort.abort(); await instance.stop(); await rm(directory, { recursive: true, force: true }); });
  const [client, concurrent] = await Promise.all([instance.start(), instance.start()]);
  assert.equal(client, concurrent);
  const pid = instance.process.pid;
  assert.equal(await instance.start(), client);
  assert.equal(instance.process.pid, pid);
  const response = await fetch(client.url + '/api/v1/apps', { headers: { authorization: 'Bearer ' + client.token } });
  assert.equal(response.status, 200);
  assert.deepEqual((await response.json()).map(app=>JSON.parse(app.body).slug).sort(), ['finder','ink-environment','preview']);
  assert.equal((await fetch(client.url + '/api/v1/apps')).status, 401);
  assert.equal(await localPort(directory), port);
  const attached = new LocalInstance({ platformDirectory: instance.platformDirectory, directory, port: port + 1 });
  t.after(() => attached.stop());
  const other = await attached.start();
  assert.equal(other.url, client.url);
  assert.equal(attached.process, undefined);
  assert.equal(attached.running, true);
  await attached.stop();
  assert.equal(instance.running, true);
  assert.equal((await fetch(client.url + '/api/health')).status, 200);
  const streams = await Promise.all(['/api/events', '/api/v1/events', '/api/v1/desktop/events?clientId=' + randomUUID()].map(path => fetch(client.url + path, { headers: { authorization: 'Bearer ' + client.token }, signal: AbortSignal.any([t.signal, abort.signal]) })));
  for (const stream of streams) assert.match(stream.headers.get('content-type'), /^text\/event-stream/);
  await instance.stop();
  for (const stream of streams) await stream.text();
  assert.notEqual(instance.process.exitCode, undefined);
  const restarted = await instance.start();
  assert.notEqual(instance.process.pid, pid);
  assert.equal(restarted.instanceId, client.instanceId);
  assert.equal(restarted.url, client.url);
  assert.equal((await fetch(restarted.url + '/api/v1/apps', { headers: { authorization: 'Bearer ' + restarted.token } })).status, 200);
});

test('an occupied saved port never receives the local credential', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'ink-desktop-address-'));
  const requests = [];
  const server = createServer((request, response) => {
    requests.push({ path: request.url, authorization: request.headers.authorization });
    response.setHeader('content-type', 'application/json'); response.end(JSON.stringify({ instanceId: 'different-instance' }));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await rm(directory, { recursive: true, force: true }); });
  const url = `http://127.0.0.1:${server.address().port}`;
  await writeFile(join(directory, 'client.json'), JSON.stringify({ url, token: 'test-local-only' }));
  await writeFile(join(directory, 'instance.json'), JSON.stringify({ id: 'expected-instance', adminToken: 'test-local-only' }));
  const instance = new LocalInstance({ platformDirectory: resolve('../ink-os-platform'), directory, port: server.address().port });
  await assert.rejects(instance.start(), /another service/);
  assert.equal(instance.process, undefined);
  assert.deepEqual(requests, [{ path: '/api/health', authorization: undefined }]);
});
